// 趋势菜名 → 菜单内菜品 的模糊匹配：
// 完全同名优先，其次包含关系（"红烧肉" 命中 "毛氏红烧肉"）
export function matchTrendDish(name, dishes) {
  return (
    dishes.find(d => d.name === name) ||
    dishes.find(d => d.name.includes(name) || name.includes(d.name)) ||
    null
  )
}
