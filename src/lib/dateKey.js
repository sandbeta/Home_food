/* ============================================================
 * 日期键唯一真源 —— 「补零」和「YYYY-MM-DD」这两件事只在这一处定义
 * ------------------------------------------------------------
 * 为什么要有它：pad2 / ymd 此前散在 anniversary.js（叫 pad+ymd）、
 * KitchenCalendar.jsx（叫 pad2+ymdStr）、DishShareCard.jsx（叫 pad2）、
 * BubbleClock（内联拼 ISO）四处，同一个语义四种写法。日历格命中、
 * 纪念日命中、分享海报日期这三条线一旦有一处补零方式跑偏，
 * 表现就是「那天明明有订单却没点亮」这类查不出根因的错。
 *
 * 纪律：只放**无时区依赖的本地日期**拼接。跨时区/UTC 口径的事别塞进来。
 * ============================================================ */

/** 两位补零：月份、日号、时分秒都走它 */
export function pad2(n) { return String(n).padStart(2, '0') }

/** 本地日期键 YYYY-MM-DD —— 日历分桶、纪念日命中、订单去重都以此为键 */
export function ymd(d) { return `${d.getFullYear()}-${pad2(d.getMonth() + 1)}-${pad2(d.getDate())}` }
