import { launchChrome, openAndSettle, screenshot, evaluate, closeChrome, sleep } from './cdp.mjs'
const stamp=Date.now(); const port=9800+(stamp%20)
const chrome=await launchChrome(port,`E:/tmp-lamb-cdp/fam${stamp}`)
const {client}=await openAndSettle({port,url:'http://localhost:8787/#/menu',wait:3200})
const errors=[]; client.on('Runtime.exceptionThrown',(p)=>errors.push(p?.exceptionDetails?.exception?.description||p?.exceptionDetails?.text))
async function waitFor(sel,timeout=12000){const t=Date.now();while(Date.now()-t<timeout){const n=await evaluate(client,`document.querySelectorAll(${JSON.stringify(sel)}).length`);if(n)return n;await sleep(250)}return 0}
console.log('family flag', await evaluate(client,'!!window.__CHENGUANG_FAMILY__'), 'rows', await waitFor('.dish-row__add'))
await evaluate(client,`document.querySelectorAll('.dish-row__add')[0]?.click()`); await sleep(400)
await evaluate(client,`document.querySelectorAll('.dish-row__add')[1]?.click()`); await sleep(500)
await evaluate(client,`location.hash='#/cart'`); await sleep(900)
await screenshot(client,'E:/tmp-lamb-shots/family-cart.png')
console.log('cart rows', await evaluate(client,`document.querySelectorAll('.cart-row').length`))
await evaluate(client,`document.querySelector('.cart-total .btn--primary')?.click()`); await sleep(1600)
console.log('after order', await evaluate(client,'location.hash'))
await screenshot(client,'E:/tmp-lamb-shots/family-order.png')
await evaluate(client,`location.hash='#/admin/orders'`); await sleep(1400)
await evaluate(client,`document.querySelector('.admin-order .btn--honey')?.click()`); await sleep(1000)
await screenshot(client,'E:/tmp-lamb-shots/family-admin.png')
console.log('admin next label', await evaluate(client,`document.querySelector('.admin-order .btn--honey')?.textContent || 'none'`))
console.log(errors.length?`ERRORS\n${errors.join('\n')}`:'no runtime errors')
await closeChrome(chrome); process.exit(0)
