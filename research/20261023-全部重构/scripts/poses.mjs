import { launchChrome, openAndSettle, screenshot, evaluate, closeChrome, sleep } from './cdp.mjs'
const base=process.env.BASE || 'http://localhost:5180'; const out='E:/tmp-lamb-shots/poses'; const stamp=Date.now(); const port=9740+(stamp%20)
const chrome=await launchChrome(port,`E:/tmp-lamb-cdp/poses${stamp}`)
const {client}=await openAndSettle({port,url:`${base}/#/today`,wait:2600})
const CART=JSON.stringify([{dish_id:1,name:'番茄牛腩煲',price:28,category:'硬菜',quantity:1,added_by:'me'},{dish_id:3,name:'可乐鸡翅',price:22,category:'家常菜',quantity:2,added_by:'partner'}])
for (const p of ['sleep','pray','play','bath','busy','steal']) {
  await evaluate(client, `location.hash = '#/today?pose=${p}'`)
  await sleep(700)
  await screenshot(client, `${out}/${p}.png`)
  console.log('pose',p)
}
await evaluate(client, `localStorage.setItem('couple_order_cart_v2', ${JSON.stringify(CART)})`)
await evaluate(client, `location.hash = '#/cart'`)
await sleep(900)
await screenshot(client, `${out}/cart.png`)
await evaluate(client, `localStorage.setItem('lamb_theme','night')`)
await evaluate(client, `location.hash = '#/today?pose=bath'`)
await sleep(900)
await screenshot(client, `${out}/bath-night.png`)
await evaluate(client, `localStorage.setItem('couple_order_cart_v2','[]')`)
await evaluate(client, `location.hash = '#/cart'`)
await sleep(900)
await screenshot(client, `${out}/cart-empty-night.png`)
await closeChrome(chrome); process.exit(0)
